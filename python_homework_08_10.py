# завдання дні тижня
dny = [
    "",
    "Понеділок",
    "Вівторок",
    "Середа",
    "Четвер",
    "П'ятниця",
    "Субота",
    "Неділя",
]
nom = int(input("Введіть номер дня тижня (від 1 до 7): "))
if 1 <= nom <= 7:
  nazva = dny[nom]
  print(f"Цей день: {nazva}")
  if nom <= 5:
    print("Це будній день")
  else:
    print("Це вихідний день")
else:
    print("Помилка! Введіть число від 1 до 7.")